"""
Builds docs/findings_report.md from the real data.

Every number in the report is calculated by this script, so the report always
matches the data. Run fetch_trials.py, analyze_trials.py and operations_view.py first.
"""
from pathlib import Path

import pandas as pd

Path("docs").mkdir(exist_ok=True)

df = pd.read_csv("data/trials_clean.csv")
cities_table = pd.read_csv("output/ops_recruiting_by_city.csv")
attention = pd.read_csv("output/ops_attention_list.csv")
duration = pd.read_csv("output/ops_duration_by_phase.csv")
footprint = pd.read_csv("output/ops_site_footprint.csv")

total = len(df)
downloaded = df["downloaded_on"].iloc[0]


def pct(part, whole=None):
    whole = total if whole is None else whole
    return f"{part / whole * 100:.0f}%" if whole else "n/a"


def count_frame(series, label):
    return pd.DataFrame({
        label: list(series.index),
        "trials": [int(v) for v in series.values],
        "share": [pct(v) for v in series.values],
    })


def md_table(frame):
    header = "| " + " | ".join(frame.columns) + " |"
    divider = "|" + "|".join(["---"] * len(frame.columns)) + "|"
    rows = ["| " + " | ".join(str(v) for v in row) + " |"
            for row in frame.itertuples(index=False)]
    return "\n".join([header, divider] + rows)


# ---------- Status ----------
status = df["status"].value_counts()
completed = int(status.get("Completed", 0))
recruiting = int(status.get("Recruiting", 0))
unknown = int(status.get("Unknown", 0))
finished = df[df["status"].isin(["Completed", "Terminated", "Withdrawn"])]
stopped = int(finished["status"].isin(["Terminated", "Withdrawn"]).sum())

# ---------- Phase ----------
phase = df["phase"].value_counts()
top_phase, top_phase_n = phase.index[0], int(phase.iloc[0])
phase3 = int(phase.get("Phase 3", 0))
no_phase = int(phase.get("Not applicable", 0))

# ---------- Sponsors ----------
sponsor_class = df["sponsor_class"].value_counts()
industry = int(sponsor_class.get("Industry", 0))
top_sponsors = df["sponsor"].value_counts().head(3)
top_sponsors_text = ", ".join(f"{name} ({int(n)})" for name, n in top_sponsors.items())

# ---------- Where trials run ----------
scope = df["scope"].value_counts()
india_only = int(scope.get("India only", 0))
multi_country = int(scope.get("India and other countries", 0))

# ---------- Time ----------
years = df["start_year"].dropna().astype(int)
year_counts = years.value_counts()
first_year, last_year = int(years.min()), int(years.max())
peak_year, peak_n = int(year_counts.idxmax()), int(year_counts.max())
since_2020 = int((years >= 2020).sum())
no_start = int(df["start_year"].isna().sum())

# ---------- Enrollment ----------
enrollment = df["enrollment"]
median_enrollment = int(enrollment.median())
largest = df.loc[enrollment.idxmax()]
largest_n = int(largest["enrollment"])
largest_title = largest["title"]
largest_id = largest["nct_id"]

# ---------- Operations ----------
top_cities_text = ", ".join(
    f"{row.city} ({row.recruiting_trials})" for row in cities_table.head(3).itertuples()
)
flag_counts = attention["flag"].value_counts()
n_flagged = int(attention["nct_id"].nunique())
single_site = int(footprint.loc[footprint["sites_in_country"] == "1 site", "trials"].sum())

all_cities = df["cities"].dropna().str.split("; ").explode()
spellings = []
if {"Bangalore", "Bengaluru"} <= set(all_cities):
    spellings.append("Bangalore and Bengaluru")
if {"Delhi", "New Delhi"} <= set(all_cities):
    spellings.append("Delhi and New Delhi")
if spellings:
    city_note = ("Some places are spelled in more than one way ("
                 + "; ".join(spellings) + "), so city counts are split.")
else:
    city_note = "City names are as typed by sponsors and were not standardised."

# ---------- Tables ----------
status_table = md_table(count_frame(status, "status"))
phase_table = md_table(count_frame(phase, "phase"))
flag_table = md_table(pd.DataFrame({
    "flag": list(flag_counts.index),
    "trials": [int(v) for v in flag_counts.values],
}))
duration_table = md_table(duration.rename(columns={
    "trials": "completed trials", "median_months": "median months"}))

report = f"""# Findings report: diabetes trials with a site in India

*Data: ClinicalTrials.gov (a service of the U.S. National Library of Medicine),
downloaded on {downloaded}. {total} trials. This report is generated by
`make_report.py`, so every number comes straight from the data.*

## Key findings

1. **Most trials are finished.** {completed} of {total} trials ({pct(completed)}) are completed, and {recruiting} are recruiting now.
2. **Trial phases.** The most common phase is {top_phase} ({top_phase_n} trials, {pct(top_phase_n)}), and {no_phase} trials ({pct(no_phase)}) have no drug phase (for example lifestyle, device or behavioural studies).
3. **Sponsors.** {industry} trials ({pct(industry)}) have an industry lead sponsor. The three most frequent sponsors are {top_sponsors_text}.
4. **Global and local trials.** {india_only} trials ({pct(india_only)}) run only in India. {multi_country} ({pct(multi_country)}) also have sites in other countries.
5. **Timing.** Start years run from {first_year} to {last_year}, with a peak in {peak_year} ({peak_n} trials). {since_2020} trials ({pct(since_2020)}) started in 2020 or later, and {no_start} have no start date.
6. **Trial size.** The median enrollment is {median_enrollment} participants. The largest registered enrollment is {largest_n:,} ({largest_id}), so medians are used instead of averages.
7. **Early stopping.** Of {len(finished)} finished trials, {stopped} ({pct(stopped, len(finished))}) were terminated or withdrawn.
8. **Operations.** {recruiting} trials are recruiting now. Cities with the most recruiting trials: {top_cities_text}. {n_flagged} trials ({pct(n_flagged)}) have at least one flag that deserves a closer look.

## Methods

- **Source:** ClinicalTrials.gov API v2, searched for the condition "diabetes" with a site in India. The registry matches related terms, so trials where diabetes is one of several conditions may be included.
- **Cleaning:** status, phase and sponsor codes were relabelled. Dates were converted, and month-only dates were treated as the end of that month when checking for overdue trials.
- **Trial scope:** trials were grouped by whether all of their sites are in India or some are elsewhere.
- **Flags:** a trial is flagged if its completion date has passed while it is still active, its start date has passed while it is still "not yet recruiting", its status is Unknown (not verified for over two years), or it is suspended.
- **Duration:** months from the registered start date to the registered completion date, for completed trials only.

## Details

### Trials by status

{status_table}

### Trials by phase

{phase_table}

### Trials needing attention

{flag_table}

A trial can carry more than one flag.

### Typical duration of completed trials

{duration_table}

Phases with only a few completed trials give unreliable medians.

### Site footprint

{single_site} trials have exactly one site in India. The footprint table is in `output/ops_site_footprint.csv`.

## Limitations

- **Snapshot:** the registry changes every day, and this report describes the data on {downloaded}.
- **Self-reported data:** sponsors enter and update their own records. A flag can simply mean the record is out of date, so flags are leads, not proof of a problem.
- **Registered, not actual:** enrollment and completion dates may be planned values.
- **Counts of trials, not people:** a trial with 38 sites in India counts once.
- **Places:** {city_note}
- **Search scope:** only trials with at least one site in India are included, and the search term may match related conditions.
- **No statistical testing:** the report describes the data and does not test differences between groups.

## What an operations team could check first

- Contact sponsors of trials with an **Unknown** status to confirm whether they are still running.
- Check trials whose registered completion date has passed but are still listed as active, since their dates may need updating.
- Look at the cities with the most recruiting trials when thinking about site capacity and competition for patients.
"""

Path("docs/findings_report.md").write_text(report, encoding="utf-8")
print(f"Wrote docs/findings_report.md ({total} trials)")